function bossChallenge(topicId: string): Challenge {
  const topic = TAXONOMY_TOPICS.find((t) => t.id === topicId);
  const name = topic?.name ?? topicId;
  const nameBn = topic?.nameBn ?? topicId;
  const base = topic?.baseDifficulty ?? 3;
  return {
    id: 'challenge.boss.' + topicId,
    kind: 'boss',
    name: name.toUpperCase() + ' BOSS',
    nameBn: nameBn + ' বস',
    description: '10 problems of increasing difficulty. Limited hints. Beat it to unlock the next stage.',
    descriptionBn: 'ক্রমশ কঠিন ১০টি সমস্যা। সীমিত সংকেত। জিতলে পরের ধাপ খুলে যাবে।',
    emoji: '👾',
    topicId,
    questionCount: 10,
    durationSeconds: 900,
    hintsAllowed: 2,
    difficultyStart: Math.max(1, base),
    difficultyEnd: Math.min(9, base + 4),
    xpReward: 250,
    coinReward: 120,
    requiredMastery: 0.5,
    contentVersion: CURRENT_CONTENT_VERSION,
  };
}

