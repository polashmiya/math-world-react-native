function buildSteps(steps: string[], stepsBn?: string[]): SolutionStep[] {
  return steps.map((detail, index) => ({
    order: index + 1,
    detail,
    detailBn: stepsBn?.[index],
  }));
}

function toQuestion(seed: QuestionSeed): Question {
  const options = seed.choices?.map((text, index) => ({
    id: 'opt' + index,
    text,
    textBn: seed.choicesBn?.[index],
  }));
  const correctAnswer =
    seed.answerIndex !== undefined ? 'opt' + seed.answerIndex : (seed.answer ?? '');

  return {
    id: seed.id,
    topicId: seed.topicId,
    subtopicId: null,
    skillIds: seed.skillIds,
    difficulty: seed.difficulty,
    questionType: seed.type,
    curriculumIds: ['bangladesh', 'international'],
    examIds: seed.examIds ?? [],
    tags: seed.tags ?? [],
    brainCategory: seed.brainCategory ?? null,
    prompt: seed.prompt,
    promptBn: seed.promptBn,
    options,
    correctAnswer,
    acceptedAnswers: undefined,
    tolerance: seed.tolerance,
    solutionSteps: buildSteps(seed.steps, seed.stepsBn),
    explanation: seed.explanation,
    explanationBn: seed.explanationBn,
    hints: seed.hints,
    hintsBn: seed.hintsBn,
    estimatedTimeSeconds: estimatedSecondsForDifficulty(seed.difficulty),
    points: pointsForDifficulty(seed.difficulty),
    source: 'static',
    generatorId: null,
    generatorParams: null,
    year: seed.year ?? null,
    questionVersion: 1,
    contentVersion: CURRENT_CONTENT_VERSION,
  };
}

export const STATIC_QUESTIONS: Question[] = SEEDS.map(toQuestion);
